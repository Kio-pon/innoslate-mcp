def make_handler(store: Store):
    class H(BaseHTTPRequestHandler):
        def log_message(self, *a):
            pass

        # --------------------------------------------------------- helpers
        def _session(self) -> str | None:
            c = SimpleCookie(self.headers.get("Cookie", ""))
            s = c.get("JSESSIONID")
            return s.value if s and s.value in store.sessions else None

        def _send(self, code, body=b"", ctype="application/json", headers=None):
            if isinstance(body, (dict, list)):
                body = json.dumps(body).encode()
            elif isinstance(body, str):
                body = body.encode()
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            for k, v in (headers or {}).items():
                self.send_header(k, v)
            self.end_headers()
            self.wfile.write(body)

        def _body(self) -> bytes:
            n = int(self.headers.get("Content-Length") or 0)
            return self.rfile.read(n) if n else b""

        # ------------------------------------------------------------ GET
        def do_GET(self):
            u = urlparse(self.path)
            q = {k: v[0] for k, v in parse_qs(u.query).items()}
            path = u.path
            port = self.server.server_address[1]
            if path == "/login":
                if store.login_style == "sso":
                    return self._send(302, "", "text/html",
                                      {"Location": f"http://localhost:{port}/sso?next={q.get('next', '/')}"})
                tpl = LOGIN_TWO_STEP if store.login_style == "two-step" else LOGIN_SINGLE
                return self._send(200, tpl.format(next=html.escape(q.get("next", "/")), err=""), "text/html")
            if path == "/sso":
                form = LOGIN_SINGLE.replace('action="/login"', f'action="http://127.0.0.1:{port}/login"')
                return self._send(200, form.format(next=html.escape(q.get("next", "/")), err=""), "text/html")
            if path.startswith("/api/"):
                if not self._session():
                    return self._send(401, {"message": "Unauthorized"})
                return self._api_get(path, q)
            m = re.match(rf"^/{ORG}/p/{PID}(/.*)?$", path)
            if m:
                if not self._session():
                    return self._send(302, "", "text/html", {"Location": f"/login?next={path}"})
                dm = re.match(r"^/documents/(\d+)$", m.group(1) or "")
                if dm:
                    did = int(dm.group(1))
                    e = store.E.get(did)
                    return self._send(200, DOC_PAGE.format(title=html.escape(e["name"] if e else "?"), org=ORG, pid=PID, doc=did), "text/html")
                return self._send(200, "<!doctype html><html><body><h1>Project Dashboard</h1></body></html>", "text/html")
            if path == "/":
                return self._send(200, "<html><body>Innoslate</body></html>", "text/html")
            return self._send(404, {"message": "not found"})

        def _api_get(self, path, q):
            o = f"/api/v4/o/{ORG}"
            p = f"{o}/p/{PID}"
            with store.lock:
                if path == p:
                    return self._send(200, {"id": PID, "name": "Dashboard Mini Project", "description": "<p>Course project.</p>"})
                if path == f"{p}/schema":
                    return self._send(200, {"classes": CLASSES, "relations": RELATIONS, "labels": LABELS,
                                            "properties": PROPERTIES, "targetedRelationIds": []})
                if path == f"{p}/entities/counts":
                    c: dict[str, int] = {}
                    for e in store.E.values():
                        c[str(e["classId"])] = c.get(str(e["classId"]), 0) + 1
                    return self._send(200, c)
                if path == f"{p}/comments":
                    return self._send(200, store.comments)
                if path == f"{p}/users":
                    return self._send(200, [{"user": "senior.dev"}, {"user": "student"}, {"user": "teammate"},
                                            {"user": "instructor", "email": "instructor@uni.example"}])
                if path == f"{p}/entities/changes":
                    return self._send(200, [])
                if path == f"{o}/entities":
                    if q.get("projectId") != str(PID):
                        return self._send(400, {"message": "projectId required"})
                    hits = store.search(q.get("query", ""))
                    lim, off = min(int(q.get("limit", 100)), 500), int(q.get("offset", 0))
                    return self._send(200, hits[off:off + lim])
                m = re.match(rf"^{o}/entities/(\d+)$", path)
                if m:
                    e = store.E.get(int(m.group(1)))
                    return self._send(200, [e]) if e else self._send(404, {"message": "no such entity"})
                if path == f"{o}/allocate_ids":
                    n = int(q.get("count", 1))
                    out = []
                    for _ in range(n):
                        store.next_id += 1
                        store.allocated.add(store.next_id)
                        out.append({"id": store.next_id, "globalId": f"I_{secrets.token_hex(6).upper()}"})
                    return self._send(200, out)
                m = re.match(rf"^{o}/files/([^/]+)$", path)
                if m:
                    f = store.files.get(unquote(m.group(1)))
                    return self._send(200, {"key": m.group(1), **{k: v for k, v in f.items() if k != "data"}}) if f else self._send(404, {})
                if path == f"{p}/report":
                    kind = q.get("type", "docx")
                    name = {"docx": "Basic Document Output.docx", "rtm": "RTM Output.xlsx", "qc": "Quality Checker Check Report.xlsx"}[kind]
                    return self._send(200, b"PK\x03\x04fake-report-" + q.get("doc", "").encode(), "application/octet-stream",
                                      {"Content-Disposition": f'attachment; filename="{name}"'})
            return self._send(404, {"message": "unknown api path"})

        # ----------------------------------------------------------- POST
        def do_POST(self):
            u = urlparse(self.path)
            q = {k: v[0] for k, v in parse_qs(u.query).items()}
            if u.path == "/login":
                form = {k: v[0] for k, v in parse_qs(self._body().decode()).items()}
                if form.get("username") == USER and form.get("password") == PASSWORD:
                    tok = secrets.token_hex(16)
                    store.sessions.add(tok)
                    port = self.server.server_address[1]
                    return self._send(302, "", "text/html", {"Location": f"http://127.0.0.1:{port}" + (form.get("next") or "/"),
                                                            "Set-Cookie": f"JSESSIONID={tok}; Path=/; HttpOnly"})
                tpl = LOGIN_TWO_STEP if store.login_style == "two-step" else LOGIN_SINGLE
                return self._send(200, tpl.format(next=html.escape(form.get("next", "/")), err="<p>Wrong password</p>"), "text/html")
            if not self._session():
                return self._send(401, {"message": "Unauthorized"})
            o = f"/api/v4/o/{ORG}"
            if u.path == f"{o}/entities":
                try:
                    payload = json.loads(self._body() or b"null")
                except ValueError:
                    return self._send(400, {"message": "bad json"})
                code, body = store.save(payload, USER)
                return self._send(code, body)
            if u.path == f"{o}/p/{PID}/files":
                ctype = self.headers.get("Content-Type", "")
                raw = self._body()
                m = re.search(r"boundary=(.+)", ctype)
                if not m:
                    return self._send(400, {"message": "multipart expected"})
                parts = raw.split(b"--" + m.group(1).encode())
                for part in parts:
                    if b'name="upload_file"' in part:
                        head, _, data = part.partition(b"\r\n\r\n")
                        fn = re.search(rb'filename="([^"]*)"', head)
                        mt = re.search(rb"Content-Type: (\S+)", head)
                        key = f"{PID}-{secrets.token_urlsafe(12)}"
                        store.files[key] = {"name": fn.group(1).decode() if fn else "file", "mime": mt.group(1).decode() if mt else "",
                                            "size": len(data.rstrip(b"\r\n")), "data": data.rstrip(b"\r\n")}
                        return self._send(200, [{"key": key}])
                return self._send(400, {"message": "no upload_file field"})
            if u.path == f"{o}/p/{PID}/qc":
                return self._send(200, {"checked": store.quality(int(q["doc"]))})
            return self._send(404, {"message": "unknown"})

    return H


